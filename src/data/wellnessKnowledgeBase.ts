/**
 * 轻量端侧 RAG 检索：根据用户提问匹配最相关的 1~2 条健身与养生知识
 */
export function retrieveWellnessKnowledge(query: string, maxItems = 2): string {
  const q = query.trim().toLowerCase();
  if (!q) return '';

  const scored = WELLNESS_KNOWLEDGE_BASE.map((entry) => {
    let score = 0;
    for (const kw of entry.keywords) {
      if (q.includes(kw.toLowerCase())) {
        score += kw.length >= 2 ? 3 : 1;
      }
    }
    return { entry, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxItems);

  if (scored.length === 0) return '';
  return scored.map(({ entry }) => `· ${entry.title}：${entry.content}`).join('\n');
}
