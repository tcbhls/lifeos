/** 按动作名快速匹配百科库条目（兼容旧分化里已有的动作名） */
export function findExerciseInLibrary(name: string): ExerciseLibraryItem | undefined {
  const clean = name.trim().toLowerCase();
  return (
    EXERCISE_LIBRARY.find((e) => e.name.toLowerCase() === clean) ||
    EXERCISE_LIBRARY.find(
      (e) => clean.includes(e.name.toLowerCase()) || e.name.toLowerCase().includes(clean),
    )
  );
}

/** 生成 B站高清示范教学直达 URL */
export function buildBilibiliVideoSearchUrl(exercise: Pick<ExerciseLibraryItem, 'name' | 'videoQuery'>): string {
  const q = encodeURIComponent(exercise.videoQuery || `${exercise.name} 标准动作 教学`);
  return `https://search.bilibili.com/all?keyword=${q}&order=totalrank`;
}

/** 从动作 ID 快速构造 WorkoutPlanExercise */
function makePlanEx(libId: string, override?: { sets?: number; min?: number; max?: number; rest?: number }) {
  const found = EXERCISE_LIBRARY.find((e) => e.id === libId) ?? EXERCISE_LIBRARY[0];
  return {
    id: `plan-${found.id}`,
    name: found.name,
    muscleGroup: found.muscleGroup.split('/')[0].trim(),
    targetSets: override?.sets ?? found.defaultSets,
    targetRepMin: override?.min ?? found.defaultRepMin,
    targetRepMax: override?.max ?? found.defaultRepMax,
    restSeconds: override?.rest ?? found.defaultRestSec,
  };
}

